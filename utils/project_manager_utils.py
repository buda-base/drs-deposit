# used only in launching DAGs.
def get_work_pm_for_step(project_step: Steps, prerequisite_step: Steps | None = None, limit: int = 1) -> list[pmItem]:
    """
    Get ProjectMembers for a work for which project_step has not been
    run on any of its volumes.
    Returns an empty list if no such work is found.
    
    :param project_step: the Steps instance for the staging step
    :type project_step: Steps
    :param prerequisite_step: optional prerequisite step that must be completed on all volumes
    :type prerequisite_step: Steps | None
    :param limit: maximum number of candidate work project members to evaluate
    :type limit: int
    :return: list of pmItem for the next works, or an empty list if no such work is found
    """
    work_pm_items: list[pmItem] = []
    with DrsDbContext(MY_DB) as db:
        session: Session = db.get_session()

        # Select Work project members where no child volume has a ProjectMemberSteps
        # row for the provided step.

        WorkPM = aliased(ProjectMembers)
        VolumePM = aliased(ProjectMembers)

        # Get all work-level ProjectMembers rows for DRS3 where there is no
        # ProjectMemberSteps row for `project_step` attached to any volume whose
        # Volumes.workId matches that work.
        stmt = (
            select(WorkPM)
            .where(
                WorkPM.project == DRS3_PROJECT, 
                WorkPM.pm_type == DRS3_WORK_TYPE,
                ~exists(
                    select(1)
                    .select_from(ProjectMemberSteps)
                    .join(VolumePM, ProjectMemberSteps.project_member_id == VolumePM.id)
                    .where(
                        ProjectMemberSteps.step_id == project_step.id,
                        VolumePM.project == DRS3_PROJECT,
                        VolumePM.pm_type == DRS3_VOLUME_TYPE,
                        VolumePM.pm_work_id == WorkPM.pm_work_id,  # correlate to outer work PM
                    )
                ),
            )
            .order_by(WorkPM.id)
            .limit(limit)
        )
        candidate_work_dtos = session.scalars(stmt).all()

        if prerequisite_step:
            for candidate_work_dto in candidate_work_dtos:
                # A candidate is valid only if every volume for the work has a
                # successful prerequisite step recorded.
                # Look at volume project members that belong to:
                # the DRS3 project,
                # the volume member type,
                # and the same work as the current candidate work.
                # Keep only volumes for which there is no matching ProjectMemberSteps
                # row where:
                # - the step is the prerequisite step,
                # - and that step has an end time (meaning it finished, regardless of success/failure).
                # So effectively: “Find volumes in this work that do *not* (~exists) have 
                # not completed the prerequisite step.”
                # For drs-deposit#126, this setp was changed so that only the end time is considered:
                # We don't want to include works that are in process, and we don't care if the volumes have failed.
                # This seems a little counterintuitive, but the code to count all the succeses
                # is frighteningly complex.
                missing_prereq_stmt = (
                    select(1)
                    .select_from(VolumePM)
                    .where(
                        VolumePM.project == DRS3_PROJECT,
                        VolumePM.pm_type == DRS3_VOLUME_TYPE,
                        VolumePM.pm_work_id == candidate_work_dto.pm_work_id,
                        ~exists(
                            select(1)
                            .select_from(ProjectMemberSteps)
                            .where(
                                ProjectMemberSteps.project_member_id == VolumePM.id,
                                ProjectMemberSteps.step_id == prerequisite_step.id,
                                #jimk drs-deposit#126 - we want to exc;ude any that have been completed,
                                # regardless of success status (used to check for return_code = 0)
                                ProjectMemberSteps.project_step_end_time.is_not(None)
                            )
                        ),
                    )
                )

                missing_prereq_volume = session.execute(missing_prereq_stmt).first()
                # This is the key part - if there is a row that has not completed (~exists(....)), there will
                # be a row present. If there is such a row, then this work is not a candidate.
                # If there is no such row, then all volumes have completed the prerequisite step,
                # and this work is a candidate.
                if not missing_prereq_volume:
                    _work_pm: pmItem =  pmItem(
                            _require_label(candidate_work_dto.work.WorkName, "work project member"),
                            candidate_work_dto.id,
                            PMTarget.PROJECT_MEMBER,
                        )
                    work_pm_items.append(_work_pm)

                    # Create the ProjectMemberStep for this work
                    # Bug - for sql get or create, you only supply the key fields
                    # in the call - because all parameters are searched for, including
                    # runtime constructs
                    work_pms, is_new = get_or_create(
                        session,
                        ProjectMemberSteps,
                        project_member = candidate_work_dto,
                        project_step=project_step,
                    )
                    logger.info(f"{'Created' if is_new else 'Found'} ProjectMemberSteps for work "
                                f"{candidate_work_dto.work.WorkName}")
                    if is_new:
                        session.commit()


        if not work_pm_items:
            logger.warning(f"No unstaged work found for step {project_step.s_name} with successful" 
                           f"prerequisite step {prerequisite_step.s_name} on all volumes")
        return work_pm_items


def get_pms_for_step(
    work_pm_item: pmItem, work_source_root: Path, project_step: Steps
) -> tuple[pmItem, list[pmItem]]:
    """
    Get or create all the ProjectMemberSteps for the volumes of this work
    that need to be operated on, and return them as a list
    :param work_pm_item: the pmItem instance for the work to stage
    :type unstaged_work_pm_item: pmItem
    :param work_source_root: the root directory for the source files of a work
    :type work_source_root: Path
    :param project_step: the Steps instance for the staging step
    :type project_step: Steps
    :return: list of pmItem for the volumes to stage
    :rtype: list[pmItem]
      """

    unstaged_volumes_pms_items: list[pmItem] = []
    with DrsDbContext(MY_DB) as db:
        session: Session = db.get_session()

        unstaged_work_pm: ProjectMembers = cast(ProjectMembers, work_pm_item.load(session))
        if not unstaged_work_pm:
            raise RuntimeError(
                f"ProjectMember not found for {work_pm_item.label} "
                f"(id={work_pm_item.o_id})"
            )

        # Create the staged step for the work ProjectMember
        unstaged_work_pms: ProjectMemberSteps 
        unstaged_work_pms, is_new = get_or_create(
            session,
            ProjectMemberSteps,
            project_member=unstaged_work_pm,
            project_step=project_step
        )
        session.flush()
        unstaged_work_pms_item : pmItem = pmItem(
            _require_label(unstaged_work_pm.work.WorkName, "work project member step"),
            {"project_member_id": unstaged_work_pm.id, "step_id": project_step.id},
            PMTarget.PROJECT_MEMBER_STEP
        )
    
        images_root = c.get_work_image_path(work_source_root)
        image_dirs = [d for d in images_root.iterdir() if d.is_dir()] if images_root.exists() else []

        # Get the ProjectMembers for the volumes in this work
        get_volume_pm_s_for_work_stmt = (
            select(ProjectMembers)
            .options(joinedload(ProjectMembers.volume))
            .where(
                ProjectMembers.project == DRS3_PROJECT,
                ProjectMembers.pm_type == DRS3_VOLUME_TYPE,
                ProjectMembers.volume.has(Volumes.workId == unstaged_work_pm.pm_work_id),  # pyright: ignore[reportArgumentType]
            )
        )
        #
        volume_pm_s_for_work = session.scalars(get_volume_pm_s_for_work_stmt).all()

        for image_dir in image_dirs:      

            # select this volume from ProjectMembers by matching folder name
            volume_pm = next(
                (
                    pm
                    for pm in volume_pm_s_for_work
                    if pm.volume is not None and pm.volume.label == image_dir.name
                ),
                None,
            )
            if not volume_pm:
                raise RuntimeError(
                    "Volume PM not found for volume with label "
                    f"{image_dir.name} in work {unstaged_work_pm.work.WorkName}"
                )
            
            # get_or_create session.flush() es, generating an id.
            volume_pms, is_new = get_or_create(
                session,
                ProjectMemberSteps,
                project_member=volume_pm,
                project_step=project_step
            )

            # Add the 
            unstaged_volumes_pms_items.append(
                pmItem(
                    _require_label(
                        volume_pm.volume.label if volume_pm.volume is not None else None,
                        "volume project member step",
                    ),
                    {"project_member_id": volume_pm.id, "step_id": project_step.id},
                     PMTarget.PROJECT_MEMBER_STEP)
            )
        session.commit()
    return unstaged_work_pms_item, unstaged_volumes_pms_items

def update_database_from_pm_items(work_pms_item: pmItem, volume_pms_items: list[pmItem]) -> None:
    """
    Complete any process for a work item and its associated volumes.
    :param work_pms_item: pmItem for the work being processed, updated out of context
    :param volume_pms_items: list of pmItems for the volumes that were processed, 
    containing opaque user data updated out of context.
    :type work_pms_item: pmItem
    :type volume_pms_items: list[pmItem]

    """

    with DrsDbContext(MY_DB) as db:
        session = db.get_session()
        upd_ok: bool = True

        # Fold in anything that was added to the pmItems
        for v_pms_item in volume_pms_items:
            try:
                v_pms = v_pms_item.load(session)
                for k, val in v_pms_item.extras.items():
                    if hasattr(v_pms, k):
                        setattr(v_pms, k, val)
                
            except Exception as e:
                upd_ok = False
                logger.error(f"Error updating volume pmItems: {v_pms_item.label} (id={v_pms_item.o_id}) Exc: {e}")

        loaded_work_pms = work_pms_item.load(session)
        if not isinstance(loaded_work_pms, ProjectMemberSteps):
            raise RuntimeError(
                f"Work pmItem did not resolve to ProjectMemberSteps: "
                f"{work_pms_item.label} (id={work_pms_item.o_id})"
            )
        db_work_pms: ProjectMemberSteps = loaded_work_pms
        for k, val in work_pms_item.extras.items():
            if hasattr(db_work_pms, k):
                setattr(db_work_pms, k, val)
        if not upd_ok:
            db_work_pms.project_step_result_code = 1
        session.commit()

