class PMTarget(enum.StrEnum):
    PROJECT_MEMBER = "project_member"
    PROJECT_MEMBER_STEP = "project_member_step"

AllowedModel: TypeAlias = ProjectMembers | ProjectMemberSteps  # noqa: UP040
ORMIdentity: TypeAlias = int | tuple[Any, ...] | Mapping[str, Any]  # noqa: UP040

TARGET_TO_MODEL: dict[PMTarget, type] = {
    PMTarget.PROJECT_MEMBER: ProjectMembers,
    PMTarget.PROJECT_MEMBER_STEP: ProjectMemberSteps,
}

@dataclass(slots=True)
class pmItem:
    """
    Github copilot generated dataset with self referential ORM.
    ACHTUNG: or as John Prine said "Listen up buster, and listen up good"
    Any dict item you put in extras **MUST** be an attr in the model_cls() of the pmItem
    Because a usage pattern (also generated by GitHub Copilot) is like this:
    (src is the pmItem, v_pmns is the ORM object loaded by pmItem.load())
    for k, val in src.extras.items():
    if hasattr(v_pms, k):
        setattr(v_pms, k, val)

    Usage Notes: 
        for a pmItem with a single primary key, you can use either a scalar or a dict for the o_id.
            For most uses, an integer scalar is sufficient, but you can use a scalar with the key name
                pmItem("x",  {"id": 10}, PMTarget.PROJECT_MEMBER)
        for a pmItem with a compound key, you can use either a tuple or a dict for the o_id.
            Tuple identity:
                pmItem("x", (10, 7), PMTarget.PROJECT_MEMBER_STEP)
            Dict identity:
                pmItem("x", {"project_member_id": 10, "project_step_id": 7}, PMTarget.PROJECT_MEMBER_STEP)
    """
    label: str
    # SQLAlchemy session.get() identity can be scalar PK, tuple for composite PK,
    # or dict keyed by PK attribute names.
    o_id: ORMIdentity
    target: PMTarget
    extras: dict[str, Any] = field(default_factory=dict)

    def model_cls(self) -> type:
        return TARGET_TO_MODEL[self.target]

    def load(self, session: Session) -> AllowedModel | None:
        obj = session.get(self.model_cls(), self.o_id)

        # Strict runtime check: id must resolve to the expected ORM type.
        if obj is not None and not isinstance(obj, self.model_cls()):
            raise TypeError(
                f"pmItem target/type mismatch: target={self.target}, "
                f"id={self.o_id}, got={type(obj).__name__}"
            )
        return obj

def _require_label(value: str | None, context: str) -> str:
    if value is None:
        raise RuntimeError(f"Missing required label for {context}")
    return value

def _get_drs3_step_name(step_name: str) -> Steps:
    """
    Pre-fetch some standard lookup model objects
    """
    with DrsDbContext(MY_DB) as db:
        session: Session = db.get_session()
        transcode_step = select(Steps).where(Steps.s_name == step_name)  # pyright: ignore[reportArgumentType]
        transcode_step = session.execute(transcode_step).scalar_one_or_none()
        if not transcode_step:
            raise RuntimeError(f"{step_name} step not found")
        return transcode_step
DRS3_STAGE_STEP = _get_drs3_step_name(c.STAGE_STEP_NAME)
DRS3_TRANSCODE_STEP = _get_drs3_step_name(c.TRANSCODE_STEP_NAME)

def _get_drs3_project_objects() -> tuple[Projects, MemberTypes, MemberTypes]:
    """
    Pre-fetch some standard lookup model objects
    """
    with DrsDbContext(MY_DB) as db:
        session = db.get_session()
        project_named_drs3 = select(Projects).where(Projects.name == c.DRS3_PROJECT_NAME)  # pyright: ignore[reportArgumentType]
        project = session.execute(project_named_drs3).scalar_one_or_none()
        if not project:
            raise RuntimeError(f"{c.DRS3_PROJECT_NAME} project not found")

        get_work_type_work = select(MemberTypes).where(MemberTypes.m_type == c.PROJECT_MEMBER_TYPE_WORK)  # pyright: ignore[reportArgumentType]
        work_type = session.execute(get_work_type_work).scalar_one_or_none()
        if not work_type:
            raise RuntimeError(f"{c.PROJECT_MEMBER_TYPE_WORK} MemberType not found")

        volume_type = session.execute(
            select(MemberTypes).where(MemberTypes.m_type == c.PROJECT_MEMBER_TYPE_VOLUME)
        ).scalar_one_or_none()
        if not volume_type:
            raise RuntimeError(f"{c.PROJECT_MEMBER_TYPE_VOLUME} MemberType not found")

        return project, work_type, volume_type

DRS3_PROJECT, DRS3_WORK_TYPE, DRS3_VOLUME_TYPE = _get_drs3_project_objects()

